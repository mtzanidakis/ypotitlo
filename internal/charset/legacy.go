package charset

import (
	"unicode/utf8"

	"golang.org/x/text/encoding"
	"golang.org/x/text/transform"
)

// singleByte is a single-byte encoding built from a table of the 128 runes the
// high half of the byte range maps to. The low half is ASCII.
//
// x/text has no charmap for cp737, cp869 or macgreek, and charmap.Charmap
// cannot be constructed from outside its package, so these three are
// implemented here. They are the encodings of pre-Unicode Greek subtitle rips:
// cp737 and cp869 from MS-DOS, macgreek from classic Mac OS.
type singleByte struct {
	name string
	dec  [128]rune
	enc  map[rune]byte
}

func newSingleByte(name string, dec [128]rune) *singleByte {
	m := &singleByte{name: name, dec: dec, enc: make(map[rune]byte, 128)}
	for i, r := range dec {
		if r == utf8.RuneError || r == 0 {
			continue
		}
		if _, dup := m.enc[r]; !dup {
			m.enc[r] = byte(0x80 + i)
		}
	}
	return m
}

func (m *singleByte) String() string { return m.name }

func (m *singleByte) NewDecoder() *encoding.Decoder {
	return &encoding.Decoder{Transformer: sbDecoder{m}}
}

func (m *singleByte) NewEncoder() *encoding.Encoder {
	return &encoding.Encoder{Transformer: sbEncoder{m}}
}

// repertoireError reports a rune that the destination encoding cannot
// represent.
//
// x/text signals this with an unexported type, but encoding.ReplaceUnsupported
// detects it structurally, through a Replacement() byte method, so an encoding
// defined outside x/text can take part in the same error handling.
type repertoireError byte

func (e repertoireError) Error() string { return "encoding: rune not supported by encoding" }

func (e repertoireError) Replacement() byte { return byte(e) }

type sbDecoder struct{ m *singleByte }

func (d sbDecoder) Reset() {}

func (d sbDecoder) Transform(dst, src []byte, _ bool) (nDst, nSrc int, err error) {
	for _, c := range src {
		r := rune(c)
		if c >= 0x80 {
			r = d.m.dec[c-0x80]
			if r == 0 {
				r = utf8.RuneError
			}
		}
		if nDst+utf8.RuneLen(r) > len(dst) {
			return nDst, nSrc, transform.ErrShortDst
		}
		nDst += utf8.EncodeRune(dst[nDst:], r)
		nSrc++
	}
	return nDst, nSrc, nil
}

type sbEncoder struct{ m *singleByte }

func (e sbEncoder) Reset() {}

func (e sbEncoder) Transform(dst, src []byte, atEOF bool) (nDst, nSrc int, err error) {
	for nSrc < len(src) {
		r, size := utf8.DecodeRune(src[nSrc:])
		if r == utf8.RuneError && size == 1 {
			if !atEOF && !utf8.FullRune(src[nSrc:]) {
				return nDst, nSrc, transform.ErrShortSrc
			}
			return nDst, nSrc, repertoireError(encoding.ASCIISub)
		}

		var c byte
		if r < utf8.RuneSelf {
			c = byte(r)
		} else {
			b, ok := e.m.enc[r]
			if !ok {
				return nDst, nSrc, repertoireError(encoding.ASCIISub)
			}
			c = b
		}
		if nDst >= len(dst) {
			return nDst, nSrc, transform.ErrShortDst
		}
		dst[nDst] = c
		nDst++
		nSrc += size
	}
	return nDst, nSrc, nil
}

